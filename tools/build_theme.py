"""Regenerate presentation tokens without touching projects or processing rules."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    theme = json.loads((ROOT / 'web/design-tokens.json').read_text(encoding='utf-8'))
    lines = [f'  --{name}: {value};' for name, value in theme['colors'].items()]
    lines.extend([f"  --font: {theme['font']};", '  --green: var(--primary);',
                  '  --dark: var(--ink);', '  --paper: var(--canvas);',
                  '  --white: var(--surface);', '  --amber: var(--warning);',
                  '  --red: var(--error);'])
    (ROOT / 'web/theme-tokens.css').write_text(
        '/* Generated by tools/build_theme.py from design-tokens.json. */\n:root {\n'
        + '\n'.join(lines) + '\n}\n', encoding='utf-8')


if __name__ == '__main__':
    build()
